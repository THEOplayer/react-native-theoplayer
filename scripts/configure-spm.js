#!/usr/bin/env node
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const moduleName = 'THEOplayerFeatures';
const modulePath = `ios/${moduleName}`;
const featureTraits = {
  GOOGLE_IMA: 'GoogleIMA',
  THEO_ADS: 'THEOads',
  MILLICAST: 'Millicast',
  SIDELOADED_TEXTTRACKS: 'SideloadedTextTracks',
  CHROMECAST: 'GoogleCast',
};

function writeIfChanged(file, contents) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === contents) {
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

function configureSpm(appRoot) {
  const config = JSON.parse(fs.readFileSync(path.join(appRoot, 'react-native-theoplayer.json'), 'utf8'));
  const features = config?.ios?.features;
  if (!Array.isArray(features) || features.some((feature) => typeof feature !== 'string')) {
    throw new Error('react-native-theoplayer.json must contain an ios.features array of strings.');
  }

  const unsupported = features.filter((feature) => !Object.hasOwn(featureTraits, feature));
  if (unsupported.length > 0) {
    throw new Error(
      `Unsupported experimental SPM features: ${unsupported.join(', ')}. Supported features: ${Object.keys(featureTraits).join(', ')}.`,
    );
  }

  const packageFile = path.join(appRoot, 'package.json');
  const packageContents = fs.readFileSync(packageFile, 'utf8');
  const appPackage = JSON.parse(packageContents);
  if (!appPackage || typeof appPackage !== 'object' || Array.isArray(appPackage)) {
    throw new Error('package.json must contain an object.');
  }
  const spmConfig = appPackage.swiftpmConfig;
  if (spmConfig !== undefined && (!spmConfig || typeof spmConfig !== 'object' || Array.isArray(spmConfig))) {
    throw new Error('package.json swiftpmConfig must be an object.');
  }
  const modules = spmConfig?.modules === undefined ? [] : spmConfig.modules;
  if (!Array.isArray(modules)) {
    throw new Error('package.json swiftpmConfig.modules must be an array.');
  }
  const selectorRoot = path.join(appRoot, modulePath);
  const registrations = modules.filter(
    (module) =>
      (typeof module?.name === 'string' && module.name.toLowerCase() === moduleName.toLowerCase()) ||
      (typeof module?.path === 'string' && path.resolve(appRoot, module.path) === selectorRoot),
  );
  if (
    registrations.length > 1 ||
    (registrations.length === 1 &&
      (registrations[0].name !== moduleName ||
        typeof registrations[0].path !== 'string' ||
        path.resolve(appRoot, registrations[0].path) !== selectorRoot))
  ) {
    throw new Error(`Conflicting swiftpmConfig.modules registration for ${moduleName} or ${modulePath}. Resolve it before running this command.`);
  }
  if (!fs.existsSync(path.join(appRoot, 'ios')) || !fs.statSync(path.join(appRoot, 'ios')).isDirectory()) {
    throw new Error('Run this command from an app root containing an ios directory.');
  }

  const traits = Object.entries(featureTraits)
    .filter(([feature]) => features.includes(feature))
    .map(([, trait]) => trait);
  // Explicit product edges avoid SwiftPM failing to resolve trait-only vendor dependencies.
  const nativeDependencies = [];
  if (features.includes('GOOGLE_IMA') || features.includes('THEO_ADS')) {
    nativeDependencies.push({
      product: 'GoogleInteractiveMediaAds',
      package: 'swift-package-manager-google-interactive-media-ads-ios',
      url: 'https://github.com/googleads/swift-package-manager-google-interactive-media-ads-ios',
      requirement: '.upToNextMajor(from: "3.31.0")',
    });
  }
  if (features.includes('MILLICAST')) {
    nativeDependencies.push({
      product: 'MillicastSDK',
      package: 'millicast-sdk-swift-package',
      url: 'https://github.com/millicast/millicast-sdk-swift-package',
      requirement: '.upToNextMinor(from: "2.7.0")',
    });
  }
  if (features.includes('SIDELOADED_TEXTTRACKS')) {
    nativeDependencies.push({
      product: 'THEOplayerConnectorSideloadedSubtitle',
      package: 'ios-connector',
      url: 'https://github.com/THEOplayer/iOS-Connector',
      requirement: '.upToNextMajor(from: "11.0.2")',
    });
  }
  if (features.includes('CHROMECAST')) {
    nativeDependencies.push({
      product: 'GoogleCastDynamic',
      package: 'google-cast-ios-sdk',
      url: 'https://github.com/googlecast/google-cast-ios-sdk',
      requirement: '.upToNextMajor(from: "4.8.0")',
    });
  }
  // RN exposes this package and the player as siblings under its generated libs directory.
  const manifest = `// swift-tools-version: 6.1
// Generated by react-native-theoplayer/scripts/configure-spm.js. Do not edit.
import PackageDescription

let package = Package(
    name: "${moduleName}",
    platforms: [.iOS("16.0")],
    products: [
        .library(
            name: "${moduleName}",
            targets: ["${moduleName}"]
        ),
    ],
    dependencies: [
        .package(
            path: "../ReactNativeTHEOplayer",
            traits: [${traits.map((trait) => JSON.stringify(trait)).join(', ')}]
        ),
${nativeDependencies
  .map(
    (dependency) => `        .package(
            url: "${dependency.url}",
            ${dependency.requirement}
        ),
`,
  )
  .join('')}    ],
    targets: [
        .target(
            name: "${moduleName}",
            dependencies: [
                .product(
                    name: "ReactNativeTHEOplayer",
                    package: "ReactNativeTHEOplayer"
                ),
${nativeDependencies
  .map(
    (dependency) => `                .product(
                    name: "${dependency.product}",
                    package: "${dependency.package}"
                ),
`,
  )
  .join('')}            ]
        ),
    ]
)
`;

  writeIfChanged(path.join(selectorRoot, 'Package.swift'), manifest);
  writeIfChanged(
    path.join(selectorRoot, 'Sources', moduleName, `${moduleName}.swift`),
    '// Generated by react-native-theoplayer/scripts/configure-spm.js. Do not edit.\nimport ReactNativeTHEOplayer\n',
  );
  if (registrations.length === 0) {
    appPackage.swiftpmConfig = { ...spmConfig, modules: [...modules, { name: moduleName, path: modulePath }] };
    const indentation = packageContents.match(/^[\t ]+(?=")/m)?.[0] ?? '  ';
    const newline = packageContents.includes('\r\n') ? '\r\n' : '\n';
    const ending = packageContents.endsWith('\n') ? newline : '';
    writeIfChanged(packageFile, JSON.stringify(appPackage, null, indentation).replace(/\n/g, newline) + ending);
    console.log(`Registered ${moduleName} in package.json swiftpmConfig.modules.`);
  }
  console.log(`Configured ${moduleName}: optional traits [${traits.join(', ')}]. THEOlive is always included.`);
}

function main() {
  const args = process.argv.slice(2);
  if (args.length === 1 && (args[0] === '--help' || args[0] === '-h')) {
    console.log(`Usage: theoplayer-features-spm [--sync]

Run from the app root to configure experimental iOS SPM features from react-native-theoplayer.json.
Supported features: ${Object.keys(featureTraits).join(', ')}.
THEOlive is always included, matching the CocoaPods setup.
iOS 16 or later is required.

  --sync      Run the app-installed React Native SPM sync after configuration.
              Requires an existing React Native SPM setup; does not migrate CocoaPods.
  --help, -h  Show this help.
`);
    return;
  }
  if (args.length > 1 || (args.length === 1 && args[0] !== '--sync')) {
    throw new Error('Usage: theoplayer-features-spm [--sync]');
  }
  const appRoot = process.cwd();
  const sync = args.includes('--sync');
  let reactNativeCli;
  if (sync) {
    if (!fs.existsSync(path.join(appRoot, 'ios', 'ReactNativeSPM', 'Scripts', 'sync-autolinking.sh'))) {
      throw new Error(
        '--sync requires an existing React Native SPM setup in ios/ReactNativeSPM. Configure RN SPM first; this command does not migrate CocoaPods.',
      );
    }
    try {
      const reactNativePackageFile = require.resolve('react-native/package.json', { paths: [appRoot] });
      const reactNativePackage = JSON.parse(fs.readFileSync(reactNativePackageFile, 'utf8'));
      // RN exports package.json, but its CLI executable is not an importable subpath.
      reactNativeCli = require.resolve(path.resolve(path.dirname(reactNativePackageFile), reactNativePackage.bin['react-native']));
    } catch {
      throw new Error('Cannot find the app-installed React Native CLI. Install the app dependencies before using --sync.');
    }
  }

  configureSpm(appRoot);
  if (sync) {
    console.log('Running React Native SPM sync...');
    const result = spawnSync(process.execPath, [reactNativeCli, 'spm', 'sync'], { cwd: appRoot, stdio: 'inherit' });
    if (result.error) {
      throw result.error;
    }
    if (result.signal) {
      throw new Error(`React Native SPM sync terminated by ${result.signal}. Generated configuration is retained.`);
    }
    process.exitCode = result.status ?? 1;
    if (process.exitCode !== 0) {
      console.error(`React Native SPM sync failed with exit code ${process.exitCode}. Generated configuration is retained.`);
    }
  } else {
    console.log('Next: npx react-native spm sync');
  }
}

try {
  main();
} catch (error) {
  console.error(`THEOplayer SPM configuration failed: ${error.message}`);
  process.exitCode = 1;
}
